package daio7771.everytunnel.platform

import daio7771.everytunnel.EveryTunnel
import daio7771.everytunnel.platform.BlockShapes.box
import net.fabricmc.fabric.api.itemgroup.v1.FabricItemGroup
import net.fabricmc.fabric.api.`object`.builder.v1.block.entity.FabricBlockEntityTypeBuilder
import net.minecraft.block.AbstractBlock
import net.minecraft.block.Block
import net.minecraft.block.MapColor
import net.minecraft.block.entity.BlockEntityType
import net.minecraft.block.piston.PistonBehavior
import net.minecraft.item.BlockItem
import net.minecraft.item.Item
import net.minecraft.item.ItemGroup
import net.minecraft.item.ItemStack
import net.minecraft.registry.Registries
import net.minecraft.registry.Registry
import net.minecraft.sound.BlockSoundGroup
import net.minecraft.text.Text
import net.minecraft.util.Identifier
import net.minecraft.util.math.Direction

/**
 * The mod's blocks: the fluorescent light and the props of the levels (pipes, ducts,
 * cable trays, boxes, cones...), which replace the re-skinned vanilla stand-ins in the
 * mod version of the generated levels. All are in the "Every Tunnel" creative tab, for
 * building by hand (`/give @s every_tunnel:<id>` works too).
 *
 * Models, textures and their LabPBR maps are generated by `tools/blocks/generate.py`;
 * the ids here and there must match (the tool warns when they don't). Shapes are in
 * pixels for the model's base orientation (see [BlockShapes]).
 */
object ModBlocks {

    private val all = mutableListOf<Pair<String, Block>>()

    val FLUORESCENT_LIGHT: Block = register(
        "fluorescent_light",
        FluorescentLightBlock(
            props(MapColor.WHITE_GRAY, BlockSoundGroup.GLASS).luminance { FluorescentLightBlock.luminance(it) },
        ),
    )

    // --- Things standing on the floor ---------------------------------------------------

    val CARDBOARD_BOX: Block = register(
        "cardboard_box",
        PropBlock(solid(MapColor.BROWN, ModSoundGroups.CARDBOARD), listOf(box(0, 0, 0, 16, 16, 16))),
    )
    val TRAFFIC_CONE: Block = register(
        "traffic_cone",
        PropBlock(props(MapColor.ORANGE, ModSoundGroups.PLASTIC), listOf(box(3, 0, 3, 13, 1, 13), box(5, 1, 5, 11, 13, 11))),
    )
    val FIRE_EXTINGUISHER: Block = register(
        "fire_extinguisher",
        PropBlock(props(MapColor.RED, ModSoundGroups.HOLLOW_METAL), listOf(box(5, 0, 5, 11, 12, 11))),
    )
    val SHOPPING_CART: Block = register(
        "shopping_cart",
        PropBlock(props(MapColor.IRON_GRAY, ModSoundGroups.WIRE_MESH), listOf(box(1, 0, 1, 15, 13, 15))),
    )
    val PALLET: Block = register(
        "pallet",
        PropBlock(props(MapColor.OAK_TAN, ModSoundGroups.WOOD), listOf(box(0, 0, 0, 16, 3, 16))),
    )
    val OIL_DRUM: Block = register(
        "oil_drum",
        PropBlock(props(MapColor.BLUE, ModSoundGroups.HOLLOW_METAL), listOf(box(2, 0, 2, 14, 16, 14))),
    )
    val TRASH_BIN: Block = register(
        "trash_bin",
        PropBlock(props(MapColor.GRAY, ModSoundGroups.PLASTIC), listOf(box(3, 0, 3, 13, 14, 13))),
    )
    val WHEEL_STOP: Block = register(
        "wheel_stop",
        PropBlock(props(MapColor.STONE_GRAY, BlockSoundGroup.STONE), listOf(box(0, 0, 5, 16, 3, 11))),
    )

    // --- Ceiling services ---------------------------------------------------------------

    val PIPE: Block = register(
        "pipe",
        ConnectingPropBlock(
            props(MapColor.IRON_GRAY, ModSoundGroups.METAL_PIPE),
            box(5, 5, 5, 11, 11, 11),
            mapOf(
                Direction.NORTH to box(5, 5, 0, 11, 11, 5), Direction.SOUTH to box(5, 5, 11, 11, 11, 16),
                Direction.WEST to box(0, 5, 5, 5, 11, 11), Direction.EAST to box(11, 5, 5, 16, 11, 11),
                Direction.UP to box(5, 11, 5, 11, 16, 11), Direction.DOWN to box(5, 0, 5, 11, 5, 11),
            ),
        ),
    )
    val DUCT: Block = register(
        "duct",
        ConnectingPropBlock(
            props(MapColor.IRON_GRAY, ModSoundGroups.SHEET_METAL),
            box(2, 3, 2, 14, 13, 14),
            mapOf(
                Direction.NORTH to box(2, 3, 0, 14, 13, 2), Direction.SOUTH to box(2, 3, 14, 14, 13, 16),
                Direction.WEST to box(0, 3, 2, 2, 13, 14), Direction.EAST to box(14, 3, 2, 16, 13, 14),
                Direction.UP to box(2, 13, 2, 14, 16, 14), Direction.DOWN to box(2, 0, 2, 14, 3, 14),
            ),
        ),
    )
    val CABLE_TRAY: Block = register(
        "cable_tray",
        ConnectingPropBlock(
            props(MapColor.IRON_GRAY, ModSoundGroups.SHEET_METAL),
            box(1, 9, 1, 15, 13, 15),
            mapOf(
                Direction.NORTH to box(1, 9, 0, 15, 13, 1), Direction.SOUTH to box(1, 9, 15, 15, 13, 16),
                Direction.WEST to box(0, 9, 1, 1, 13, 15), Direction.EAST to box(15, 9, 1, 16, 13, 15),
            ),
        ),
    )
    val HANGING_CABLE: Block = register(
        "hanging_cable",
        PropBlock(props(MapColor.BLACK, ModSoundGroups.PLASTIC).noCollision(), listOf(box(6, 0, 6, 10, 16, 10))),
    )

    // --- Surfaces -------------------------------------------------------------------------

    val METAL_PANEL: Block = register("metal_panel", Block(solid(MapColor.IRON_GRAY, ModSoundGroups.SHEET_METAL)))
    /** Sliding elevator door; closed and opened by a level's intro (IntroHooks). */
    val ELEVATOR_DOOR: Block = register(
        "elevator_door",
        ElevatorDoorBlock(solid(MapColor.IRON_GRAY, ModSoundGroups.SHEET_METAL).nonOpaque().pistonBehavior(PistonBehavior.BLOCK)),
    )
    /** Loot lying around, picked up with right-click (LootBlock, placed by LootSpawner). */
    val LOOT_BATTERY: Block = register("loot_battery", LootBlock(props(MapColor.CLEAR, BlockSoundGroup.STONE).noCollision()) { ModItems.BATTERY })
    val LOOT_WATER_BOTTLE: Block = register(
        "loot_water_bottle",
        LootBlock(props(MapColor.CLEAR, BlockSoundGroup.STONE).noCollision()) { ModItems.WATER_BOTTLE },
    )

    val LOOT_KEYCARD: Block = register(
        "loot_keycard",
        LootBlock(props(MapColor.CLEAR, BlockSoundGroup.STONE).noCollision()) { ModItems.KEYCARD },
    )

    /** A keycard reader on a wall: opens the iron doors next to it for a player with the keycard. */
    val CARD_READER: Block = register(
        "card_reader",
        CardReaderBlock(props(MapColor.BLACK, ModSoundGroups.PLASTIC).luminance { 2 }.noCollision()),
    )

    /** Shared by the loot blocks; registered in [register]. */
    lateinit var LOOT_ENTITY: BlockEntityType<LootBlockEntity>
        private set

    /** Rolling shutter curtain; closed behind the player when they walk into the next level (LevelEntryHooks). */
    val SHUTTER: Block = register(
        "shutter",
        ShutterBlock(solid(MapColor.IRON_GRAY, ModSoundGroups.SHEET_METAL).nonOpaque().pistonBehavior(PistonBehavior.BLOCK)),
    )
    val SIGN_TILE: Block = register("sign_tile", SignTileBlock(solid(MapColor.LIGHT_GRAY, BlockSoundGroup.STONE)))
    val STAIN: Block = register("stain", StainBlock(props(MapColor.CLEAR, BlockSoundGroup.STONE).noCollision()))
    val PUDDLE: Block = register("puddle", PuddleBlock(props(MapColor.WATER_BLUE, ModSoundGroups.PUDDLE).noCollision()))

    /** Settings for a full, solid block. */
    private fun solid(color: MapColor, sounds: BlockSoundGroup): AbstractBlock.Settings =
        AbstractBlock.Settings.create().mapColor(color).strength(0.3f).sounds(sounds)

    /** Settings for a block that does not fill its space (light and other blocks show around it). */
    private fun props(color: MapColor, sounds: BlockSoundGroup): AbstractBlock.Settings =
        solid(color, sounds).nonOpaque().pistonBehavior(PistonBehavior.DESTROY)

    private fun register(id: String, block: Block): Block = block.also { all += id to it }

    fun register() {
        val items = all.map { (id, block) ->
            val identifier = Identifier(EveryTunnel.MOD_ID, id)
            Registry.register(Registries.BLOCK, identifier, block)
            Registry.register(Registries.ITEM, identifier, BlockItem(block, Item.Settings()))
        }
        LOOT_ENTITY = Registry.register(
            Registries.BLOCK_ENTITY_TYPE, Identifier(EveryTunnel.MOD_ID, "loot"),
            FabricBlockEntityTypeBuilder.create(::LootBlockEntity, LOOT_BATTERY, LOOT_WATER_BOTTLE, LOOT_KEYCARD).build(),
        )
        val tab: ItemGroup = FabricItemGroup.builder()
            .icon { ItemStack(FLUORESCENT_LIGHT) }
            .displayName(Text.translatable("itemGroup.every_tunnel"))
            .entries { _, entries ->
                items.forEach { entries.add(it) }
                entries.add(ModEntities.PALE_MAN_SPAWN_EGG)
            }
            .build()
        Registry.register(Registries.ITEM_GROUP, Identifier(EveryTunnel.MOD_ID, "blocks"), tab)
    }
}
