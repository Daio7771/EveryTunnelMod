# Takes that end before their text does (the generator cut them): how many of the text's sentences the voice says. The
# rest of the text shows after the voice, unvoiced, as long as it takes to read (READ_MS_PER_CHAR, at least
# MIN_TAIL_CUE_MS a cue), and the line's length covers it, so the scene waits for it.
CUT_TAKES = {"meeting_07": 1, "meeting_08_b": 1, "meeting_09": 1}
READ_MS_PER_CHAR = 65
MIN_TAIL_CUE_MS = 1500

GROUPS = {"union": UNION, "rowan": ROWAN}
LINES = UNION + ROWAN


def pa_filter(x, sr=44100):
    """A loudspeaker's voice (the announcements of `rowan_loyal_*`): band-limited like a small horn, a little drive so it breaks up on
    loud words, and a short slap of the corridor behind it. Back to the clean line's loudness."""
    from scipy import signal
    band = signal.butter(4, [380.0, 3600.0], btype="band", fs=sr, output="sos")
    y = signal.sosfilt(band, x)
    y = np.tanh(2.2 * y) / np.tanh(2.2)
    room = np.zeros_like(y)
    for delay_ms, gain in ((38, 0.22), (91, 0.12), (143, 0.06)):
        d = int(sr * delay_ms / 1000)
        room[d:] += y[:-d] * gain
    y = y + signal.sosfilt(signal.butter(2, 2500.0, btype="low", fs=sr, output="sos"), room)
    y *= np.sqrt(np.mean(x ** 2)) / max(np.sqrt(np.mean(y ** 2)), 1e-9)
    ceiling = 0.97
    peak = np.max(np.abs(y))
    return y * (ceiling / peak) if peak > ceiling else y


def md5(path):
    return hashlib.md5(path.read_bytes()).hexdigest()


def convert(group):
    """Mono 44.1 kHz Ogg of every line of [group] from its MP3, all with the group's one gain."""
    source = SOURCES[group]
    lines = GROUPS[group]
    paths = [source / name for _, name, _ in lines]
    missing = [p.name for p in paths if not p.exists()]
    if missing:
        raise SystemExit(f"{source}: missing {', '.join(missing)}")
    sums = [md5(p) for p in paths]
    if len(set(sums)) != len(sums):
        raise SystemExit(f"{source}: two of the MP3s are the same file")
    gain = prologue_voices.group_gain_db(paths)
    factor = 10 ** (gain / 20.0)
    VOICE.mkdir(parents=True, exist_ok=True)
    for (line_id, _, _), path in zip(lines, paths):
        x = prologue_voices.decode(path) * factor
        if line_id.startswith("rowan_loyal_"):
            x = pa_filter(x)
        peak = 20 * np.log10(np.max(np.abs(x)))
        audio_io.write_ogg(VOICE / f"{line_id}.ogg", x, 44100, OGG_QUALITY)
        print(f"{line_id}: {len(x) / 44100:5.2f} s, peak {peak:5.1f} dBFS")
    print(f"{group}: gain {gain:+.2f} dB on the {len(lines)} (group at {prologue_voices.TARGET_LUFS} LUFS or the peak ceiling)")


def read(line_id):
    x, sr = audio_io.read(VOICE / f"{line_id}.ogg")
    if x.ndim > 1:
        x = x.mean(axis=1)
    assert sr == 44100, f"{line_id}: {sr} Hz"
    return x


def text_key(line_id):
    """The lang key of a line's text: its id without the `_a` or `_b` that says who speaks (meeting_03_a -> meeting_03)."""
    return PREFIX + re.sub(r"_[ab]$", "", line_id)


def cue_groups(text):
    """[(first sentence, sentence it ends before, cue text)]: voices.cue_texts's grouping, keeping which sentences each has."""
    sentences = voices.sentences(text)
    groups = []
    for i, s in enumerate(sentences):          # sentences gathered while short
        if groups and len(groups[-1][2]) + 1 + len(s) <= voices.CUE_CHARS:
            groups[-1] = (groups[-1][0], i + 1, groups[-1][2] + " " + s)
        else:
            groups.append((i, i + 1, s))
    out = []
    for g in groups:                           # a very short cue goes with the next one, if both fit two lines
        if out and len(out[-1][2]) < voices.SHORT_CUE and len(out[-1][2]) + 1 + len(g[2]) <= voices.TWO_LINES:
            out[-1] = (out[-1][0], g[1], out[-1][2] + " " + g[2])
        else:
            out.append(g)
    return out


def timed_cues(line_id, text):
    """[(ms from the line's start, first sentence, sentence it ends before, cue text)] and the line's length in ms:
    voices.timed_cues on this tool's files. A cut take (CUT_TAKES) is timed on the sentences it says, then the rest
    follows unvoiced."""
    x = read(line_id)
    sentences = voices.sentences(text)
    said_count = CUT_TAKES.get(line_id, len(sentences))
    text = " ".join(sentences[:said_count])
    groups = cue_groups(text)
    gaps, start, end = voices.pauses(x)
    total = voices.spoken(text)
    out = [(0, *groups[0])]
    said = 0
    for prev, group in zip(groups, groups[1:]):
        said += voices.spoken(prev[2])
        guess = start + (end - start) * said / total
        near = [g for g in gaps if abs((g[0] + g[1]) / 2 - guess) <= voices.SNAP_MS and g[1] - voices.LEAD_MS > out[-1][0]]
        at = min(near, key=lambda g: abs((g[0] + g[1]) / 2 - guess))[1] - voices.LEAD_MS if near else guess
        out.append((int(max(at, out[-1][0] + 1)), *group))
    ms = int(len(x) * 1000 / 44100)
    merged = []
    for cue in out:                            # too short to read alone: it goes with the one before
        if merged and cue[0] - merged[-1][0] < MIN_CUE_MS:
            merged[-1] = (merged[-1][0], merged[-1][1], cue[2], merged[-1][3] + " " + cue[3])
        else:
            merged.append(cue)
    if len(merged) > 1 and ms - merged[-1][0] < MIN_LAST_CUE_MS:
        last = merged.pop()
        merged[-1] = (merged[-1][0], merged[-1][1], last[2], merged[-1][3] + " " + last[3])
    for first, end, cue in cue_groups(" ".join(sentences[said_count:])):   # the unvoiced rest, after the voice
        merged.append((ms, said_count + first, said_count + end, cue))
        ms += max(MIN_TAIL_CUE_MS, len(cue) * READ_MS_PER_CHAR)
    return merged, ms


def main():
    if all(source.is_dir() for source in SOURCES.values()):
        for group in GROUPS:
            convert(group)
    elif not all((VOICE / f"{line_id}.ogg").exists() for line_id, _, _ in LINES):
        raise SystemExit(f"no MP3s in {', '.join(map(str, SOURCES.values()))} and not every Ogg in {VOICE}")
    english = json.loads(LANG.read_text(encoding="utf-8"))
    scene = {"lines": []}
    total = 0
    for line_id, _, speaker in LINES:
        key = text_key(line_id)
        if key not in english:
            raise SystemExit(f"{key} is missing from en_us.json: {line_id} has no text")
        if SPEAKER + speaker not in english:
            raise SystemExit(f"{SPEAKER + speaker} is missing from en_us.json")
        cues, ms = timed_cues(line_id, english[key])
        total += ms
        entry = {"id": line_id, "text": key, "speaker": SPEAKER + speaker, "ms": ms, "cues": []}
        for i, (at, first, end, cue) in enumerate(cues):
            cue_entry = {"at": at, "from": first}
            if i < len(cues) - 1:                  # the last cue goes on to the end of the text, whatever the language
                cue_entry["to"] = end
            entry["cues"].append(cue_entry)
            print(f"{line_id} {at / 1000:5.2f}/{ms / 1000:5.2f} s  {cue}")
        scene["lines"].append(entry)
    SCENE.parent.mkdir(parents=True, exist_ok=True)
    SCENE.write_text(json.dumps(scene, indent=2) + "\n", encoding="utf-8")
    print(f"{len(LINES)} lines, {total / 1000:.1f} s of voice")


def sounds():
    """(sound id, file path under sounds/, samples) of every voice file, for export.py."""
    for line_id, _, _ in LINES:
        yield f"voice.{line_id}", f"voice/ch2l1/{line_id}", read(line_id)


if __name__ == "__main__":
    sys.exit(main())
