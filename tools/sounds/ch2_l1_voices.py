"""
Chapter 2, Level 1's voices: the coworker's and the union's (follow_*, meeting_*) and Rowan's (rowan_loyal_*, the
loudspeaker; rowan_office_*, his office), and their subtitles.

Like the director's and the prologue's, they are the mod's one AI exception in sound (docs/en/audio.md, "AI voices"):
ElevenLabs library voices generated by the project's author. They arrive as MP3 files, by default in
~/Documents/Union (follow_01.mp3, meeting_1.mp3, meeting_3_A.mp3 ...) and ~/Documents/Rowan (row1.mp3 to row6.mp3,
row_sus1.mp3 to row_sus8.mp3); this tool turns them into mono Ogg, 44.1 kHz, in voice/ch2l1/ under the ids of the plan
(follow_01, meeting_03_a, rowan_loyal_a1, rowan_office_c1 ...). Each of the two groups, the union's (18 files, three
speakers of one scene) and Rowan's (14, one voice), gets one and the same gain, so that the group sits at -18 LUFS (as
the director's lines do) and keeps its balance, the true peak kept under -1.5 dBTP. export.py puts each into the mod as
`voice.<id>` (voice.follow_01 ...). Nothing here plays them: the levels' systems do, and the client's
`Ch2L1Subtitles` shows the subtitles of any of them that plays, `/playsound` included.

The subtitles are the author's: one lang key per line (`every_tunnel.ch2.l1.follow_01`, `.meeting_03` for `meeting_03_a`,
`.rowan_office_c8` ...), with the English and the Spanish text in the lang files (written in tools/lang/src/chapter2/, merged by tools/lang/build.py), which this tool only reads.
It cuts each line into cues the way voices.py cuts the director's (sentences gathered while short, each cue placed at
the pause that fits) but writes the cues as **ranges of sentences** of the line's text (first sentence, and the one
it ends before), not as texts: the client splits the translated text into sentences and shows the range, so a cue's time
is the same in every language and a line is edited in the lang files alone. A sentence ends at ".", "?" or "!"
followed by a space (`Ch2L1Sentences`, the same rule), and the English and Spanish texts must have the same number of
them (Ch2L1VoicesTest checks it). Every line has a speaker, the lang key of the name that shows before its cues in grey
(`every_tunnel.ch2.l1.speaker.*`, in the lang files).

Run (from the repository root):   python3 tools/sounds/ch2_l1_voices.py
Without the MP3 folders it uses the Ogg files already in voice/ch2l1/, so the cues can be redone anywhere.

Writes into src/main/resources/assets/every_tunnel/ (committed with the mod):
  cutscene/ch2_l1_voices.json   each line's text key, speaker, length and cues (ms from the line's start, sentence range)
and prints every cue with its time, to check them by ear.
"""

