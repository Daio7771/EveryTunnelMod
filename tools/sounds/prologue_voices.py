"""
The scientist's voice (Chapter 2's prologue): his four lines, and their subtitles.

The voices are the mod's one AI exception in sound (docs/en/audio.md, "AI voices"): ElevenLabs library voices
generated by the project's author. They arrive as four MP3 files (prol_1.mp3 to prol_4.mp3, by default in
~/Documents/PrologueVoices); this tool turns them into mono Ogg, 44.1 kHz, in voice/ as prologue_01.ogg to
prologue_04.ogg, all four with one and the same gain so that the group sits at -18 LUFS (as the director's
lines do) and keeps its balance (the whispers stay quiet, the screams loud), the true peak kept under -1.5 dBTP.
Two of them are finished for the transformation. The third is cut right after its last "loud" (so that the Pale
man's sound enters with no silence between); from "WHAT'S HAPPENING" on it, and the whole of the fourth, are the
same voice three times over, in step: the original, a copy a fifth and more down (a bigger body) and a copy a
fifth up (a thin one), mixed together, brought down in level and squeezed so that it is no longer a raw human
scream but something that has it in it; the layers come in over the third line's first words, so the voice
turns, and the fourth ends dry, just before the cut to black. The first two are as recorded. export.py puts each into the mod as `voice.<id>` (prologue_01 ...), played
flat by `client.cutscene.CutsceneView`.

The subtitles come whole, a cue at a time, never ahead of the voice, cut as the director's are (voices.py:
sentences joined while short), but each cue begins where [align_cues] puts it: this voice is slow, tired and
uneven, and voices.py's guess (by letters, over the whole line) put two cues up to a second and a half late. Here
the pauses are told apart by the punctuation: the line's chunks (cut at every full stop, comma and ellipsis) are
spread over the time it is actually voiced, pauses not counted, and each cue starts at the pause that fits best.
No speaker's name before them: he is nobody the game names.

Run (from the repository root):   python3 tools/sounds/prologue_voices.py [FOLDER WITH THE MP3s [ID ...]]
With ids (prologue_03 prologue_04) only those files are written again (Ogg files differ by bytes every time they
are encoded, so the ones that did not change are left alone); the gain is always the group's.

Writes into src/main/resources/assets/every_tunnel/ (committed with the mod):
  cutscene/prologue.json   each line's length and cues (ms from the line's start, lang key)
  lang/en_us.json          the cues' text, under subtitle.every_tunnel.ch2.<id>_<n>
(the Spanish subtitles are written by hand in es_es.json, then tools/lang/spanish_variants.py) and prints every
cue with its time, to check them by ear.
"""

import itertools
import json
import re
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import audio_io  # noqa: E402
import voices  # noqa: E402

HERE = Path(__file__).resolve().parent
VOICE = voices.VOICE
ASSETS = voices.ASSETS
SCENE = ASSETS / "cutscene" / "prologue.json"
LANG = voices.LANG
KEY = "subtitle.every_tunnel.ch2."
DEFAULT_SOURCE = Path.home() / "Documents" / "PrologueVoices"

# The group's loudness and its peak ceiling, as the director's lines.
TARGET_LUFS = -18.0
TRUE_PEAK_DB = -1.5

# His lines, in order: (id, the MP3 it comes from, text exactly as the voice says it).
LINES = [
    ("prologue_01", "prol_1.mp3", "Log entry. Day six. Samples are stable, readings within range. Same as yesterday, really."),
    # The recording ends at "tomorrow": the closing "I always say tomorrow." of the first script was cut by the author.
    ("prologue_02", "prol_2.mp3", "The counter keeps climbing, but it's probably the old sensor. I'll replace it tomorrow."),
    ("prologue_03", "prol_3.mp3", "Something's wrong... my hands... WHAT'S HAPPENING?! IT'S SO LOUD! EVERYTHING IS SO LOUD!"),
    ("prologue_04", "prol_4.mp3", "MY EYES! I CAN'T— AAAAAHHH!"),
]


def decode(path):
    """The file as mono samples at 44.1 kHz (ffmpeg)."""
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", "44100", "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype="<f4").astype(np.float64)


def group_gain_db(paths):
    """The one gain (dB) that brings the four files together to TARGET_LUFS, held back where it would pass the peak ceiling."""
    inputs = [arg for p in paths for arg in ("-i", str(p))]
    chain = "".join(f"[{i}:a]" for i in range(len(paths))) + f"concat=n={len(paths)}:v=0:a=1,loudnorm=I={TARGET_LUFS}:TP={TRUE_PEAK_DB}:print_format=json"
    out = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", *inputs, "-filter_complex", chain, "-f", "null", "-"],
                         capture_output=True, text=True, check=True).stderr
    stats = json.loads(out[out.rindex("{"):out.rindex("}") + 1])
    return min(TARGET_LUFS - float(stats["input_i"]), TRUE_PEAK_DB - float(stats["input_tp"]))


# How far under the loudest frame the voice is still "there", the frames it is measured in, and what stays after it.
VOICED_DB = -45.0
FRAME = 0.010
TAIL_PAD = 0.06


def cut_after_last_word(x, sr=44100):
    """The line without what follows its last sound: cut a moment after the last frame that is still voiced."""
    step = int(sr * FRAME)
    n = len(x) // step
    frames = x[:n * step].reshape(n, step)
    db = 10 * np.log10(np.mean(frames ** 2, axis=1) + 1e-12)
    last = int(np.flatnonzero(db > db.max() + VOICED_DB)[-1])
    end = min(len(x), int((last + 1) * step + TAIL_PAD * sr))
    y = x[:end].copy()
    fade = int(0.02 * sr)
    y[-fade:] *= np.linspace(1.0, 0.0, fade)
    return y


# The layers: how far each copy is moved (semitones) and how loud each is, and the result's level against the original
# (dB) and its squeeze (tanh drive). The layers come in over RAMP seconds from the line's chosen start.
DEEP, HIGH = -7.0, 7.0
LAYERS = (0.55, 0.9, 0.45)          # the original, the deep copy, the high copy
LEVEL_DB = -4.0
SQUEEZE = 1.6
RAMP = 0.8


def shifted(x, semitones, sr=44100):
    """[x] moved by [semitones] with its length and its pace kept (ffmpeg's rubberband)."""
    with tempfile.TemporaryDirectory() as tmp:
        source, result = Path(tmp) / "in.wav", Path(tmp) / "out.wav"
        with wave.open(str(source), "wb") as out:
            out.setnchannels(1)
            out.setsampwidth(2)
            out.setframerate(sr)
            out.writeframes((np.clip(x, -1.0, 1.0) * 32767).astype("<i2").tobytes())
        ratio = 2 ** (semitones / 12.0)
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(source), "-af", f"rubberband=pitch={ratio:.5f}:transients=crisp", str(result)],
                       check=True)
        y = decode(result)
    return np.pad(y, (0, max(0, len(x) - len(y))))[:len(x)]


def three_layers(start_ms):
    """A finish for a line: from [start_ms] the voice is the original, a deep copy and a high copy, together."""
    def finish(x, sr=44100):
        first = int(start_ms * sr / 1000)
        deep, high = shifted(x, DEEP, sr), shifted(x, HIGH, sr)
        mix = LAYERS[0] * x + LAYERS[1] * deep + LAYERS[2] * high
        ramp = np.clip((np.arange(len(x)) - first) / (RAMP * sr), 0.0, 1.0)
        ramp = ramp * ramp * (3.0 - 2.0 * ramp)
        live = slice(first, len(x))
        level = np.sqrt(np.mean(x[live] ** 2) + 1e-12)
        gain = level * 10 ** (LEVEL_DB / 20.0) / (np.sqrt(np.mean(mix[live] ** 2)) + 1e-12)
        wet = np.tanh(SQUEEZE * mix * gain / (np.max(np.abs(x)) + 1e-12)) * np.max(np.abs(x)) / np.tanh(SQUEEZE)
        out = (1.0 - ramp) * x + ramp * wet
        fade = int(0.004 * sr)
        out[-fade:] *= np.linspace(1.0, 0.0, fade)
        return out
    return finish


# What is done to a line after its gain, by id.
# The third is cut, then layered from "WHAT'S HAPPENING" (its second cue, 3.0 s in); the fourth is layered whole.
FINISH = {
    "prologue_03": lambda x: three_layers(3000)(cut_after_last_word(x)),
    "prologue_04": three_layers(0),
}


# Cues placed by hand where [align_cues] cannot tell: {line id: {cue index: ms from the line's start}}. The first line is
# said slowly, a word at a time ("Log... entry... day... six."), in seven stretches of voice, so no pace or punctuation
# says where its cues fall. Measured against a speech recognizer's segments (faster-whisper, tiny.en, run once for this) and
# the waveform: the cue "Samples are stable, readings within range." begins with the fifth stretch (4.84 s) and "Same as
# yesterday, really." with the seventh (7.90 s), each placed LEAD_MS ahead of its first sound.
CUE_AT_MS = {"prologue_01": {1: 4800, 2: 7860}}

# What a long pause is worth in the choice of a cue's pause (ms squared of distance).
LONG_PAUSE_REWARD = 150_000


def syllables(text):
    """A rough count of the syllables in [text] (vowel groups, at least one in each word)."""
    return sum(max(1, len(re.findall(r"[aeiouy]+", word.lower()))) for word in re.findall(r"[A-Za-z']+", text))


def chunks(text):
    """[text] cut after each full stop, question or exclamation mark, comma and ellipsis (where the voice may pause)."""
    return [c.strip() for c in re.split(r"(?<=[.?!,])\s+|(?<=\.\.\.)\s*", text.strip()) if c.strip()]


def align_cues(line_id, text):
    """[(ms from the line's start, cue text)], like voices.timed_cues but placed by the pauses' fit to the punctuation."""
    x, sr = audio_io.read(VOICE / f"{line_id}.ogg")
    if x.ndim > 1:
        x = x.mean(axis=1)
    texts = voices.cue_texts(text)
    gaps, start, end = voices.pauses(x)
    voiced = (end - start) - sum(b - a for a, b in gaps)
    # Where each pause falls in the time the line is voiced (pauses before it taken out).
    before, gone = [], 0
    for a, b in gaps:
        before.append(a - start - gone)
        gone += b - a
    # Where each cue's start should fall: the syllables before it, as a share of all of them, over the voiced time.
    counts = [syllables(t) for t in texts]
    wanted = [voiced * sum(counts[:i + 1]) / sum(counts) for i in range(len(texts) - 1)]
    best, choice = None, None
    for picks in itertools.combinations(range(len(gaps)), len(texts) - 1):
        # How far each pause is from where its cue should start, less a reward for a long pause (a full stop) over a short one.
        error = sum((before[p] - w) ** 2 for p, w in zip(picks, wanted)) - LONG_PAUSE_REWARD * sum(min(gaps[p][1] - gaps[p][0], 600) / 600 for p in picks)
        if best is None or error < best:
            best, choice = error, picks
    out = [(0, texts[0])]
    for i, (p, cue) in enumerate(zip(choice, texts[1:]), start=1):
        at = CUE_AT_MS.get(line_id, {}).get(i, gaps[p][1] - voices.LEAD_MS)
        out.append((int(max(at, out[-1][0] + 1)), cue))
    return out, int(len(x) * 1000 / sr)


def convert(source, only=()):
    paths = [source / name for _, name, _ in LINES]
    missing = [p.name for p in paths if not p.exists()]
    if missing:
        raise SystemExit(f"{source}: missing {', '.join(missing)}")
    gain = group_gain_db(paths)
    factor = 10 ** (gain / 20.0)
    VOICE.mkdir(parents=True, exist_ok=True)
    for (line_id, _, _), path in zip(LINES, paths):
        if only and line_id not in only:
            continue
        x = decode(path) * factor
        if line_id in FINISH:
            x = FINISH[line_id](x)
        peak = 20 * np.log10(np.max(np.abs(x)))
        audio_io.write_ogg(VOICE / f"{line_id}.ogg", x, 44100, 0.6)
        print(f"{line_id}: {len(x) / 44100:5.2f} s, peak {peak:5.1f} dBFS")
    print(f"gain {gain:+.2f} dB on the four (group at {TARGET_LUFS} LUFS or the peak ceiling)")


def main():
    source = Path(sys.argv[1]).expanduser() if len(sys.argv) > 1 else DEFAULT_SOURCE
    if source.is_dir():
        convert(source, tuple(sys.argv[2:]))
    elif not all((VOICE / f"{line_id}.ogg").exists() for line_id, _, _ in LINES):
        raise SystemExit(f"no MP3s in {source} and no prologue_0N.ogg in voice/")
    lang = json.loads(LANG.read_text(encoding="utf-8"))
    lang = {k: v for k, v in lang.items() if not k.startswith(KEY)}
    scene = {"lines": []}
    total = 0
    for line_id, _, text in LINES:
        cues, ms = align_cues(line_id, text)
        total += ms
        entry = {"id": line_id, "part": 0, "ms": ms, "cues": []}
        for i, (at, cue) in enumerate(cues):
            key = f"{KEY}{line_id}_{i + 1}"
            lang[key] = cue
            entry["cues"].append({"at": at, "text": key})
            print(f"{line_id} {at / 1000:5.2f}/{ms / 1000:5.2f} s  {cue}")
        scene["lines"].append(entry)
    SCENE.parent.mkdir(parents=True, exist_ok=True)
    SCENE.write_text(json.dumps(scene, indent=2) + "\n", encoding="utf-8")
    LANG.write_text(json.dumps(lang, indent=2) + "\n", encoding="utf-8")
    print(f"{len(LINES)} lines, {total / 1000:.1f} s of voice")


def sounds():
    """(sound id, file path under sounds/, samples) of every voice file, for export.py."""
    for line_id, _, _ in LINES:
        x, sr = audio_io.read(VOICE / f"{line_id}.ogg")
        if x.ndim > 1:
            x = x.mean(axis=1)
        yield f"voice.{line_id}", f"voice/prologue/{line_id}", x


if __name__ == "__main__":
    sys.exit(main())
