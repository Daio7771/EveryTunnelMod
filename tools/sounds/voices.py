# A cue gathers sentences while it stays this short; a longer sentence is a cue of its own.
CUE_CHARS = 45
# A cue this short goes with the next one (if both fit two lines), not alone for a blink.
SHORT_CUE = 12
TWO_LINES = 84

FRAME_MS = 10
SILENCE_DB = -35.0          # under the line's loudest frame
MIN_PAUSE_MS = 90
SNAP_MS = 700               # how far from its estimate a cue looks for its pause
LEAD_MS = 40                # a cue shows this long before the voice resumes


def sentences(text):
    return [s for s in re.split(r"(?<=[.?!])\s+", text.strip()) if s]


def cue_texts(text):
    """The line's cues: sentences gathered while short, a short one joined to the next."""
    cues = []
    for s in sentences(text):
        if cues and len(cues[-1]) + 1 + len(s) <= CUE_CHARS:
            cues[-1] += " " + s
        else:
            cues.append(s)
    out = []
    for c in cues:
        if out and len(out[-1]) < SHORT_CUE and len(out[-1]) + 1 + len(c) <= TWO_LINES:
            out[-1] += " " + c
        else:
            out.append(c)
    return out


def spoken(text):
    """How much there is to say: its letters and digits."""
    return sum(ch.isalnum() for ch in text)


def pauses(x):
    """The line's pauses inside its speech, as (start_ms, end_ms)."""
    n = len(x) // (44100 * FRAME_MS // 1000)
    frames = x[:n * 441].reshape(n, 441)
    db = 10 * np.log10(np.mean(frames ** 2, axis=1) + 1e-12)
    quiet = db < db.max() + SILENCE_DB
    voiced = np.flatnonzero(~quiet)
    first, last = voiced[0], voiced[-1]
    out, run = [], None
    for i in range(first, last + 1):
        if quiet[i] and run is None:
            run = i
        elif not quiet[i] and run is not None:
            if (i - run) * FRAME_MS >= MIN_PAUSE_MS:
                out.append((run * FRAME_MS, i * FRAME_MS))
            run = None
    return out, first * FRAME_MS, (last + 1) * FRAME_MS


def timed_cues(line_id, text):
    """[(ms from the line's start, cue text)]: the first at 0, each next one where its words begin."""
    x, sr = audio_io.read(VOICE / f"{line_id}.ogg")
    if x.ndim > 1:
        x = x.mean(axis=1)
    assert sr == 44100, f"{line_id}: {sr} Hz"
    texts = cue_texts(text)
    gaps, start, end = pauses(x)
    total = spoken(text)
    out = [(0, texts[0])]
    said = 0
    for prev, cue in zip(texts, texts[1:]):
        said += spoken(prev)
        guess = start + (end - start) * said / total
        near = [g for g in gaps if abs((g[0] + g[1]) / 2 - guess) <= SNAP_MS and g[1] > out[-1][0]]
        at = min(near, key=lambda g: abs((g[0] + g[1]) / 2 - guess))[1] - LEAD_MS if near else guess
        out.append((int(max(at, out[-1][0] + 1)), cue))
    return out, int(len(x) * 1000 / sr)


def main():
    durations = {}
    scene = {"lines": [], "loop": []}
    lang = json.loads(LANG.read_text(encoding="utf-8"))
    lang = {k: v for k, v in lang.items() if not k.startswith(KEY)}
    lang[SPEAKER] = "DIRECTOR:"
    for group, items in (("lines", LINES), ("loop", LOOP)):
        for line_id, part, text in items:
            cues, ms = timed_cues(line_id, text)
            durations[line_id] = ms
            entry = {"id": line_id, "part": part, "ms": ms, "cues": []}
            for i, (at, cue) in enumerate(cues):
                key = f"{KEY}{line_id}_{i + 1}"
                lang[key] = cue
                entry["cues"].append({"at": at, "text": key})
                print(f"{line_id} {at / 1000:5.2f}/{ms / 1000:5.2f} s  {cue}")
            scene[group].append(entry)
    SCENE.parent.mkdir(parents=True, exist_ok=True)
    SCENE.write_text(json.dumps(scene, indent=2) + "\n", encoding="utf-8")
    LANG.write_text(json.dumps(lang, indent=2) + "\n", encoding="utf-8")
    print(f"{len(LINES)} lines, {len(LOOP)} loop phrases, {sum(durations.values()) / 1000:.1f} s of voice")


def sounds():
    """(sound id, file path under sounds/, samples) of every voice file, for export.py."""
    for line_id, _, _ in LINES + LOOP:
        x, sr = audio_io.read(VOICE / f"{line_id}.ogg")
        if x.ndim > 1:
            x = x.mean(axis=1)
        yield f"voice.director.{line_id}", f"voice/director/{line_id}", x


if __name__ == "__main__":
    sys.exit(main())
