"""
The director's voice (Level 5's cinematic): his lines and the phrases he repeats afterwards, and their
subtitles.

The voices are the one AI exception in the mod's sound (docs/en/audio.md): ElevenLabs library voices
generated by the project's author, cut one file per line and loudness-matched by them (mono Ogg, 44.1 kHz,
-18 LUFS together), kept in voice/ (see voice/SOURCES.md). export.py puts each into the mod as
`voice.director.<id>` as it is, with no normalizing of its own, so the lines keep their balance.

The subtitles come whole, a cue at a time, never ahead of the voice: each line is split into sentences, and
neighbouring ones joined while they stay short (CUE_CHARS); a cue begins where the voice begins saying it,
found in the line's audio as the pause nearest to where its words should start.

Run (from the repository root):   python3 tools/sounds/voices.py

Writes into src/main/resources/assets/every_tunnel/ (committed with the mod):
  cutscene/director.json     each line's part, length and cues (ms from the line's start, lang key)
  lang/en_us.json            the cues' text, under subtitle.every_tunnel.director.*, and his name before them
and prints every cue with its time, to check them by ear.
"""

